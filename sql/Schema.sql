                                  `order_number` int2 NOT NULL COMMENT '빈칸 답안의 순서 번호',
                                  PRIMARY KEY (`answered_id`),
                                  CONSTRAINT `fk_answered_blank_history_id` FOREIGN KEY (`history_id`) REFERENCES `member_quiz_history` (`history_id`)
