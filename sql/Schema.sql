USE `project_easycoding`;

SET NAMES utf8mb4;
SET FOREIGN_KEY_CHECKS = 0;

DROP TABLE IF EXISTS
    `answered_option`,
    `answered_blank`,
    `member_quiz_history`,
    `answer_option`,
    `answer_blank`,
    `quiz`,
    `member_and_quiz_category`,
    `quiz_category`,
    `quiz_type`,
    `comment`,
    `post`,
    `post_category`,
    `member`;

SET FOREIGN_KEY_CHECKS = 1;

CREATE TABLE `member` (
                          `member_id` bigint NOT NULL AUTO_INCREMENT COMMENT '회원 고유 식별자',
                          `login_id` varchar(255) NULL COMMENT '소셜로그인에서 사용하는 인증받은 토큰값',
                          `email` varchar(127) NOT NULL COMMENT '로그인에 사용하는 실제 ID값',
                          `password` varchar(60) COMMENT 'BCrypt 방식으로 암호화된 비밀번호',
                          `nickname` varchar(15) NOT NULL COMMENT '서비스에서 사용하는 회원 별명',
                          `created_at` timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '회원 가입 일시',
                          `profile_id` int2 NOT NULL DEFAULT 1 COMMENT '회원 프로필 식별자',
                          `deleted_at` timestamp NULL DEFAULT NULL COMMENT '회원 탈퇴 처리 일시',
                          PRIMARY KEY (`member_id`)
) COMMENT = '회원 계정 및 기본 프로필 정보를 관리하는 테이블';

CREATE TABLE `post_category` (
                                 `category_id` int2 NOT NULL AUTO_INCREMENT COMMENT '게시글 카테고리 고유 식별자',
                                 `category` varchar(31) NOT NULL COMMENT '게시글 카테고리 이름',
                                 PRIMARY KEY (`category_id`)
) COMMENT = '게시글 분류를 관리하는 테이블';

CREATE TABLE `post` (
                        `post_id` bigint NOT NULL AUTO_INCREMENT COMMENT '게시글 고유 식별자',
                        `member_id` bigint NULL COMMENT '게시글 작성 회원의 식별자',
                        `category_id` int2 NOT NULL COMMENT '게시글 카테고리 식별자',
                        `title` varchar(63) NOT NULL COMMENT '게시글 제목',
                        `content` text NOT NULL COMMENT '게시글 본문 내용',
                        `views` int2 NOT NULL DEFAULT 0 COMMENT '게시글 조회 수',
                        `created_at` timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '게시글 작성 일시',
                        `updated_at` timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '게시글 최종 수정 일시',
                        `deleted_at` timestamp NULL DEFAULT NULL COMMENT '게시글 삭제 처리 일시',
                        PRIMARY KEY (`post_id`),
                        CONSTRAINT `fk_post_member_id` FOREIGN KEY (`member_id`) REFERENCES `member` (`member_id`),
                        CONSTRAINT `fk_post_category_id` FOREIGN KEY (`category_id`) REFERENCES `post_category` (`category_id`)
) COMMENT = '회원이 작성한 게시글 정보를 관리하는 테이블';

CREATE TABLE `comment` (
                           `comment_id` bigint NOT NULL AUTO_INCREMENT COMMENT '댓글 고유 식별자',
                           `member_id` bigint COMMENT '댓글 작성 회원의 식별자',
                           `post_id` bigint NOT NULL COMMENT '댓글이 작성된 게시글의 식별자',
                           `parent_id` bigint NULL COMMENT '부모 댓글의 식별자, 일반 댓글이면 NULL',
                           `content` varchar(255) NOT NULL COMMENT '댓글 내용',
                           `created_at` timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '댓글 작성 일시',
                           `deleted_at` timestamp NULL DEFAULT NULL COMMENT '댓글 삭제 처리 일시',
                           `updated_at` timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '댓글 최종 수정 일시',
                           PRIMARY KEY (`comment_id`),
                           CONSTRAINT `fk_comment_member_id` FOREIGN KEY (`member_id`) REFERENCES `member` (`member_id`),
                           CONSTRAINT `fk_comment_post_id` FOREIGN KEY (`post_id`) REFERENCES `post` (`post_id`),
                           CONSTRAINT `fk_comment_parent_id` FOREIGN KEY (`parent_id`) REFERENCES `comment` (`comment_id`)
) COMMENT = '게시글에 작성된 댓글 및 대댓글 정보를 관리하는 테이블';

CREATE TABLE `quiz_type` (
                             `type_id` int2 NOT NULL AUTO_INCREMENT COMMENT '퀴즈 유형 고유 식별자',
                             `type_name` varchar(15) NOT NULL COMMENT '퀴즈 유형 이름',
                             PRIMARY KEY (`type_id`)
) COMMENT = '퀴즈의 출제 유형을 관리하는 테이블';

CREATE TABLE `quiz_category` (
                                 `category_id` int2 NOT NULL AUTO_INCREMENT COMMENT '퀴즈 카테고리 고유 식별자',
                                 `category_name` varchar(127) NOT NULL COMMENT '퀴즈 카테고리 이름',
                                 PRIMARY KEY (`category_id`)
) COMMENT = '퀴즈의 과목 또는 주제 분류를 관리하는 테이블';

CREATE TABLE `member_and_quiz_category` (
                                            `member_id` bigint NOT NULL COMMENT '회원 식별자',
                                            `category_id` int2 NOT NULL COMMENT '회원이 관심 등록한 퀴즈 카테고리 식별자',
                                            PRIMARY KEY (`member_id`, `category_id`),
                                            CONSTRAINT `fk_member_and_quiz_category_member_id` FOREIGN KEY (`member_id`) REFERENCES `member` (`member_id`),
                                            CONSTRAINT `fk_member_and_quiz_category_category_id` FOREIGN KEY (`category_id`) REFERENCES `quiz_category` (`category_id`)
) COMMENT = '회원이 관심 또는 즐겨찾기한 퀴즈 카테고리를 연결하는 테이블';

CREATE TABLE `quiz` (
                        `quiz_id` bigint NOT NULL AUTO_INCREMENT COMMENT '퀴즈 고유 식별자',
                        `type_id` int2 NOT NULL COMMENT '퀴즈 출제 유형 식별자',
                        `category_id` int2 NOT NULL COMMENT '퀴즈 카테고리 식별자',
                        `title` varchar(127) NOT NULL COMMENT '퀴즈 제목',
                        `content` text NOT NULL COMMENT '퀴즈 문제 내용',
                        `explanation` text NOT NULL COMMENT '퀴즈 문제의 정답 해설',
                        `created_at` timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '퀴즈 등록 일시',
                        PRIMARY KEY (`quiz_id`),
                        CONSTRAINT `fk_quiz_type_id` FOREIGN KEY (`type_id`) REFERENCES `quiz_type` (`type_id`),
                        CONSTRAINT `fk_quiz_category_id` FOREIGN KEY (`category_id`) REFERENCES `quiz_category` (`category_id`)
) COMMENT = '퀴즈 문제, 해설 및 출제 유형 정보를 관리하는 테이블';

CREATE TABLE `answer_blank` (
                                `answer_id` bigint NOT NULL AUTO_INCREMENT COMMENT '주관식 정답 고유 식별자',
                                `quiz_id` bigint NOT NULL COMMENT '정답이 속한 퀴즈 식별자',
                                `correct_text` varchar(127) NOT NULL COMMENT '정답으로 인정되는 텍스트',
                                `order_number` int2 NOT NULL COMMENT '빈칸 또는 정답의 순서 번호',
                                PRIMARY KEY (`answer_id`),
                                CONSTRAINT `fk_answer_blank_quiz_id` FOREIGN KEY (`quiz_id`) REFERENCES `quiz` (`quiz_id`)
) COMMENT = '주관식 또는 빈칸 채우기 퀴즈의 정답을 관리하는 테이블';

CREATE TABLE `answer_option` (
                                 `answer_id` bigint NOT NULL AUTO_INCREMENT COMMENT '객관식 선택지 고유 식별자',
                                 `quiz_id` bigint NOT NULL COMMENT '선택지가 속한 퀴즈 식별자',
                                 `content` text NOT NULL COMMENT '객관식 선택지 내용',
                                 `is_correct` boolean NOT NULL COMMENT '정답 선택지 여부',
                                 `option_number` int2 NOT NULL COMMENT '선택지 순서 번호',
                                 PRIMARY KEY (`answer_id`),
                                 CONSTRAINT `fk_answer_option_quiz_id` FOREIGN KEY (`quiz_id`) REFERENCES `quiz` (`quiz_id`)
) COMMENT = '객관식 퀴즈의 선택지와 정답 여부를 관리하는 테이블';

CREATE TABLE `member_quiz_history` (
                                       `history_id` bigint NOT NULL AUTO_INCREMENT COMMENT '퀴즈 응시 이력 고유 식별자',
                                       `member_id` bigint NOT NULL COMMENT '퀴즈를 응시한 회원 식별자',
                                       `quiz_id` bigint NOT NULL COMMENT '응시한 퀴즈 식별자',
                                       `exam_at` timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '퀴즈 응시 일시',
                                       `answered` boolean NOT NULL DEFAULT FALSE COMMENT '퀴즈 답안 제출 여부',
                                       `correct` boolean DEFAULT NULL COMMENT '퀴즈 정답 여부, 미채점 시 NULL',
                                       PRIMARY KEY (`history_id`),
                                       CONSTRAINT `fk_member_quiz_history_member_id` FOREIGN KEY (`member_id`) REFERENCES `member` (`member_id`),
                                       CONSTRAINT `fk_member_quiz_history_quiz_id` FOREIGN KEY (`quiz_id`) REFERENCES `quiz` (`quiz_id`),
                                       INDEX `idx_history_exam_at` (`exam_at`)
) COMMENT = '회원의 퀴즈 응시 이력과 채점 결과를 관리하는 테이블';

CREATE TABLE `answered_blank` (
                                  `answered_id` bigint NOT NULL AUTO_INCREMENT COMMENT '주관식 제출 답안 고유 식별자',
                                  `history_id` bigint NOT NULL COMMENT '퀴즈 응시 이력 식별자',
